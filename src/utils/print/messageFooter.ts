/** WhatsApp supports clickable URLs, but not Markdown links with custom labels. */
export function withNafidFooter(message: string): string {
  const body = message.trimEnd().replace(/(?:\n\n)?— \*Generated by Nafid POS\*(?:\nhttps:\/\/nafid\.emirateswebfusion\.com\/?)?$/, '').trimEnd();
  return `${body}\n\n— *Generated by Nafid POS*\nhttps://nafid.emirateswebfusion.com`;
}
