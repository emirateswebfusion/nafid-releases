import { expect, it } from 'vitest';
import { withNafidFooter } from '../../electron/whatsapp/messageFooter';
import { formatWhatsAppBillMessage, formatWhatsAppStatementMessage, formatWhatsAppStaffSalaryMessage, formatWhatsAppLedgerTxMessage } from '../../src/utils/print/whatsappBillHelper';
import { buildBillShares } from '../../src/utils/print/whatsappSharing';
import { DEFAULT_CHECKLIST, generateWhatsAppClosingMessage, getSampleClosingSummary } from '../../src/utils/time/shopClosingHelper';
import { formatClosingWhatsAppMessage } from '../../electron/whatsapp/shopClosingMessage';

it('includes one branded website footer in every message type and bill format', () => {
  const sample = getSampleClosingSummary();
  const messages = [
    formatWhatsAppBillMessage({ shopName: 'Shop', invoiceNumber: '1', date: '2026-10-31', items: [], grandTotal: 10 }),
    formatWhatsAppStatementMessage({ shopName: 'Shop', partyName: 'Customer', balance: 10, entryCount: 1 }),
    formatWhatsAppStaffSalaryMessage({ shopName: 'Shop', staffName: 'Staff', currentBalance: 10 }),
    ...['Got Cash', 'Purchase Bill #1'].map(description => formatWhatsAppLedgerTxMessage({ openingBalance: 0, amount: 10, newBalance: 10, paymentMethod: 'CASH', description })),
    generateWhatsAppClosingMessage(sample, DEFAULT_CHECKLIST),
    formatClosingWhatsAppMessage(sample, DEFAULT_CHECKLIST),
  ];
  const input = { phone: '123', message: messages[0], a4Html: '<p>Invoice</p>', receiptText: 'Receipt', invoiceNumber: '1' };
  for (const formats of [['text'], ['a4'], ['thermal'], ['text', 'a4', 'thermal']] as const) {
    messages.push(...buildBillShares(input, [...formats]).map(share => share.message));
  }
  for (const message of messages) {
    expect(message.match(/Generated by Nafid POS/g)).toHaveLength(1);
    expect(message).toContain('— *Generated by Nafid POS*\nhttps://nafid.emirateswebfusion.com');
    expect(withNafidFooter(message)).toBe(message.trimEnd());
  }
});

it('upgrades the old footer without duplicating the credit', () => {
  expect(withNafidFooter('Report\n\n— *Generated by Nafid POS*')).toBe(withNafidFooter('Report'));
});
